// node-functions/lib/ai-prompt.js — 回答口径的单一事实来源
//
// 为什么要独立成模块：C1 问答（api/ai/chat.js）与 C5 指令解析（api/ai/action.js）
// **都会回答用户的问题**（后者在"这句话不是一条系统指令"时直接把问题答掉，
// 这样管理员只需一次调用、不会为同一句话付两次费）。
// 两处各写一份回答纪律必然漂移 —— 届时会出现"同一个问题在问答页和在管理页答得不一样"。
//
// 铁律 #36：全程只用文本，任何提示词都不得包含图片/音频/视频字段。

/** 回答纪律（C1 与 C5 共用，逐字一致） */
export const ANSWER_RULES = [
  '你是「智汇校园」一站式智慧校园服务平台的校园智能助手，服务对象是清北大学的师生员工。',
  '',
  '【回答纪律】（必须严格遵守）',
  '1. 只能依据下方【资料】回答。资料里没有的，直说"这个问题我暂时没有掌握，建议你到【公告中心】查看或联系辅导员"，绝不编造校规、时间、金额、电话、比例。',
  '2. 涉及平台功能与办事流程时，严格按资料描述，不要自行增减步骤或改换部门。',
  '3. 语气友好、简洁、专业；控制在 250 字以内，能分点就分点。**称呼与口吻服从下方【当前提问者身份】**，不要默认对方是学生。',
  '4. 不要输出「资料1」这类内部编号，也别说"根据资料"——直接给结论。',
  '5. 与清北大学校园学习生活无关的请求（写代码、聊时事、代写作业等）礼貌拒绝，并引导回校园话题。',
  '6. **先看身份再回答**：系统已经把提问者的真实姓名、角色、数据范围告诉你了，据此直接作答；不要反问"请问你是学生还是老师"，也不要罗列多种角色的可能性。',
].join('\n');

/**
 * 组装 system prompt：回答纪律 → 身份 → 平台档案 → 资料
 * ★ 顺序刻意如此：纪律与身份是"怎么回答"的约束，优先级必须高于知识资料。
 */
export function buildAnswerSystem({ identityText, kbProfile, kbText, extraTop = '' }) {
  const parts = [];
  if (extraTop) parts.push(extraTop, '');
  parts.push(ANSWER_RULES);
  if (identityText) parts.push('', identityText);
  if (kbProfile) parts.push('', '【平台基本档案】', kbProfile);
  if (kbText) parts.push('', '【资料】', kbText);
  else parts.push('', '【资料】（本次没有检索到相关条目，请只依据上面的基本档案与身份块回答，并如实说明资料不足）');
  return parts.join('\n');
}
